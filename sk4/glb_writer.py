"""Minimal binary-glTF writer, sized for whole map tiles.

the arena builder reads GLB with SharpGLTF and passes vertex positions through
unchanged, so what this module writes is already Skate 3 world space. It is
hand-rolled rather than delegating to a glTF library because the buffers here are
tens of megabytes of pre-transformed world geometry and we want them written
straight from numpy with no per-vertex Python.
"""
from __future__ import annotations

import json
import struct
from dataclasses import dataclass, field

import numpy as np

COMPONENT_FLOAT = 5126
COMPONENT_USHORT = 5123
COMPONENT_UINT = 5125
TARGET_ARRAY_BUFFER = 34962
TARGET_ELEMENT_ARRAY = 34963


def _drop_degenerate(pos, indices, eps: float = 1e-12):
    """Indices with geometrically zero-area triangles removed, plus the count dropped.

    mesh_io already drops faces whose INDICES repeat, but that misses the ones that matter
    here: three DISTINCT vertices sitting at the same (or a collinear) position. Those carry
    no area, so they have no usable normal -- see `_unit_normals` -- and, worse, no split
    plane separates them, which is what makes the arena builder's kd-tree run past its depth limit
    and abort with e.g.

        Leaf depth=33, tris=600            (RwcKdtreeMaxDepth is 32)

    600 triangles that cannot be separated in 33 splits are coincident, not merely dense.
    Idarkopf died exactly this way. Dropping them is safe: a zero-area triangle contributes
    nothing to what you see or what you ride.
    """
    t = np.ascontiguousarray(indices).reshape(-1, 3)
    if len(t) == 0:
        return t.reshape(-1), 0
    v = np.asarray(pos, dtype=np.float64)
    a, b, c = v[t[:, 0]], v[t[:, 1]], v[t[:, 2]]
    # twice the triangle area, via the cross product of two edges
    area2 = np.linalg.norm(np.cross(b - a, c - a), axis=1)
    keep = np.isfinite(area2) & (area2 > eps)
    return t[keep].reshape(-1), int((~keep).sum())


def _unit_normals(n) -> np.ndarray:
    """Normals as glTF requires them: finite and unit length.

    The spec says NORMAL must be unit vectors, and SharpGLTF enforces it -- the arena builder
    aborts the whole build on the first bad one with

        Accessor[17] NORMAL[291]: Invalid NormalModel generated by <d2s3 ...> seems to be
        malformed

    which surfaces as a System.AggregateException that reads like a tiling failure but
    happens while merely OPENING the GLB, before any tile is built. BC Bikepark died this
    way. Degenerate triangles (zero area) and some Unity source meshes both yield zero-length
    or NaN normals, so sanitising at the write boundary covers every producer at once.
    Anything unusable becomes +Y, which is a sane default for ground-ish geometry.
    """
    a = np.ascontiguousarray(n, dtype=np.float32).reshape(-1, 3)
    a = np.nan_to_num(a, nan=0.0, posinf=0.0, neginf=0.0)
    ln = np.linalg.norm(a, axis=1)
    bad = ln < 1e-6
    a[bad] = (0.0, 1.0, 0.0)
    ln[bad] = 1.0
    return np.ascontiguousarray(a / ln[:, None], dtype=np.float32)


@dataclass
class Primitive:
    positions: np.ndarray            # (n, 3) float32
    indices: np.ndarray              # (m, 3) int
    normals: np.ndarray | None = None
    uv0: np.ndarray | None = None
    uv1: np.ndarray | None = None
    material: int | None = None      # index into GlbBuilder.materials


@dataclass
class Material:
    name: str
    base_color_texture: int | None = None   # index into GlbBuilder.images
    base_color: tuple = (1.0, 1.0, 1.0, 1.0)
    # Index into GlbBuilder.images for the metallic-roughness map. the arena builder resolves its
    # SPECULAR channel from this when it is present, and only AUTO-GENERATES one from the
    # diffuse when it is absent -- and its generated map comes out near-black against our
    # albedo, which the engine serves as WHITE. See export.ExportOptions.material_roughness.
    metallic_roughness_texture: int | None = None
    # Same story for the normal channel: absent it, the arena builder SYNTHESISES a normal map by
    # running a Sobel filter over the albedo, which invents bumps out of colour variation.
    normal_texture: int | None = None
    # the arena builder maps glTF EMISSIVE -> the game's LIGHTMAP channel (Occlusion is its
    # fallback). With neither present it binds the base game's `default_white`, so every
    # surface in a converted map is lit as if its baked lightmap were pure white -- the
    # brightest value the channel can hold, on the shader family (environment.default) whose
    # whole job is to composite the diffuse against baked light. Stock content ships real,
    # mostly-dark lightmaps. See export.ExportOptions.material_lightmap.
    emissive_texture: int | None = None
    # TEXCOORD set the lightmap is sampled with. the arena builder packs exactly two UV streams:
    # TEX0 for the diffuse and TEX1 for the texCoord named here (clamped to 0..1).
    emissive_texcoord: int = 0
    # glTF transparency. the arena builder IGNORES alphaMode: it keeps the diffuse alpha (BC3) only
    # when blenrose_materials.json says `diffuse_has_alpha`, and the cut-out itself comes from
    # the shading family named there. These fields keep previews and Blender honest.
    alpha_mode: str | None = None       # None = OPAQUE, else 'MASK' or 'BLEND'
    alpha_cutoff: float = 0.5
    double_sided: bool = True


class GlbBuilder:
    def __init__(self):
        self.meshes: list[tuple[str, list[Primitive]]] = []
        self.materials: list[Material] = []
        self.images: list[tuple[str, bytes, str]] = []   # (name, png bytes, mime)
        # Zero-area triangles removed while writing; reported so a map that is full of them
        # is visible rather than silently repaired.
        self.degenerate_dropped = 0

    def add_mesh(self, name: str, primitives: list[Primitive]):
        self.meshes.append((name, primitives))

    def add_material(self, mat: Material) -> int:
        self.materials.append(mat)
        return len(self.materials) - 1

    def add_image(self, name: str, data: bytes, mime: str = "image/png") -> int:
        self.images.append((name, data, mime))
        return len(self.images) - 1

    # -- writing ----------------------------------------------------------
    def write(self, path: str):
        buf = bytearray()
        views: list[dict] = []
        accessors: list[dict] = []

        def add_view(data: bytes, target: int | None = None, stride: int | None = None) -> int:
            # glTF requires 4-byte aligned bufferView offsets.
            while len(buf) % 4:
                buf.append(0)
            offset = len(buf)
            buf.extend(data)
            v = {"buffer": 0, "byteOffset": offset, "byteLength": len(data)}
            if target is not None:
                v["target"] = target
            if stride is not None:
                v["byteStride"] = stride
            views.append(v)
            return len(views) - 1

        def add_accessor(arr: np.ndarray, ctype: int, atype: str, target: int,
                         minmax: bool = False) -> int:
            arr = np.ascontiguousarray(arr)
            view = add_view(arr.tobytes(), target)
            a = {
                "bufferView": view,
                "componentType": ctype,
                "count": int(arr.shape[0]),
                "type": atype,
            }
            if minmax:
                a["min"] = [float(x) for x in arr.min(axis=0)]
                a["max"] = [float(x) for x in arr.max(axis=0)]
            accessors.append(a)
            return len(accessors) - 1

        gltf_meshes = []
        nodes = []
        for name, prims in self.meshes:
            gprims = []
            for p in prims:
                pos = np.ascontiguousarray(p.positions, dtype=np.float32)
                attrs = {"POSITION": add_accessor(pos, COMPONENT_FLOAT, "VEC3",
                                                  TARGET_ARRAY_BUFFER, minmax=True)}
                if p.normals is not None:
                    attrs["NORMAL"] = add_accessor(
                        _unit_normals(p.normals),
                        COMPONENT_FLOAT, "VEC3", TARGET_ARRAY_BUFFER)
                if p.uv0 is not None:
                    attrs["TEXCOORD_0"] = add_accessor(
                        np.ascontiguousarray(p.uv0, dtype=np.float32),
                        COMPONENT_FLOAT, "VEC2", TARGET_ARRAY_BUFFER)
                if p.uv1 is not None:
                    attrs["TEXCOORD_1"] = add_accessor(
                        np.ascontiguousarray(p.uv1, dtype=np.float32),
                        COMPONENT_FLOAT, "VEC2", TARGET_ARRAY_BUFFER)

                idx, _degen = _drop_degenerate(pos, p.indices)
                self.degenerate_dropped += _degen
                if len(idx) == 0:
                    continue
                if len(pos) <= 65535:
                    idx = idx.astype(np.uint16)
                    ctype = COMPONENT_USHORT
                else:
                    idx = idx.astype(np.uint32)
                    ctype = COMPONENT_UINT
                iacc = add_accessor(idx.reshape(-1, 1), ctype, "SCALAR",
                                    TARGET_ELEMENT_ARRAY)
                accessors[iacc]["count"] = int(idx.size)

                gp = {"attributes": attrs, "indices": iacc, "mode": 4}
                if p.material is not None:
                    gp["material"] = int(p.material)
                gprims.append(gp)
            gltf_meshes.append({"name": name, "primitives": gprims})
            nodes.append({"name": name, "mesh": len(gltf_meshes) - 1})

        gltf_images = []
        for iname, data, mime in self.images:
            view = add_view(data)
            gltf_images.append({"name": iname, "bufferView": view, "mimeType": mime})

        gltf_materials = []
        gltf_textures = []
        for m in self.materials:
            pbr = {
                "baseColorFactor": list(m.base_color),
                "metallicFactor": 0.0,
                "roughnessFactor": 1.0,
            }
            if m.base_color_texture is not None:
                gltf_textures.append({"source": int(m.base_color_texture)})
                pbr["baseColorTexture"] = {"index": len(gltf_textures) - 1}
            if m.metallic_roughness_texture is not None:
                gltf_textures.append({"source": int(m.metallic_roughness_texture)})
                pbr["metallicRoughnessTexture"] = {"index": len(gltf_textures) - 1}
            entry = {
                "name": m.name,
                "pbrMetallicRoughness": pbr,
                "doubleSided": bool(m.double_sided),
            }
            if m.alpha_mode:
                entry["alphaMode"] = m.alpha_mode
                if m.alpha_mode == "MASK":
                    entry["alphaCutoff"] = float(m.alpha_cutoff)
            if m.normal_texture is not None:
                gltf_textures.append({"source": int(m.normal_texture)})
                entry["normalTexture"] = {"index": len(gltf_textures) - 1}
            if m.emissive_texture is not None:
                gltf_textures.append({"source": int(m.emissive_texture)})
                entry["emissiveTexture"] = {"index": len(gltf_textures) - 1}
                if m.emissive_texcoord:
                    entry["emissiveTexture"]["texCoord"] = int(m.emissive_texcoord)
                # Without a non-zero factor a glTF reader is entitled to treat the
                # emissive channel as absent.
                entry["emissiveFactor"] = [1.0, 1.0, 1.0]
            gltf_materials.append(entry)

        gltf = {
            "asset": {"version": "2.0", "generator": "d2s3 (Descenders -> Skate 3)"},
            "scene": 0,
            "scenes": [{"nodes": list(range(len(nodes)))}],
            "nodes": nodes,
            "meshes": gltf_meshes,
            "accessors": accessors,
            "bufferViews": views,
            "buffers": [{"byteLength": len(buf)}],
        }
        if gltf_materials:
            gltf["materials"] = gltf_materials
        if gltf_textures:
            gltf["textures"] = gltf_textures
            gltf["samplers"] = [{"wrapS": 10497, "wrapT": 10497}]
        if gltf_images:
            gltf["images"] = gltf_images

        json_bytes = json.dumps(gltf, separators=(",", ":")).encode("utf-8")
        json_bytes += b" " * ((4 - len(json_bytes) % 4) % 4)
        bin_bytes = bytes(buf)
        bin_bytes += b"\0" * ((4 - len(bin_bytes) % 4) % 4)

        total = 12 + 8 + len(json_bytes) + 8 + len(bin_bytes)
        with open(path, "wb") as f:
            f.write(struct.pack("<III", 0x46546C67, 2, total))
            f.write(struct.pack("<II", len(json_bytes), 0x4E4F534A))
            f.write(json_bytes)
            f.write(struct.pack("<II", len(bin_bytes), 0x004E4942))
            f.write(bin_bytes)
        return total
